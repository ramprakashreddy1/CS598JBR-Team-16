def prompt_model(dataset, model_name = "deepseek-ai/deepseek-coder-6.7b-base", quantization = True):
    print(f"Working with {model_name} quantization {quantization}...")

    # TODO: download the model
    import ast, re, textwrap
    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
    is_instruct = "instruct" in model_name

    if quantization:
        # TODO: load the model with quantization
        bnb_config = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_use_double_quant=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.bfloat16,
        )
        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            quantization_config=bnb_config,
            device_map="auto",
            torch_dtype=torch.bfloat16,
            trust_remote_code=True,
        )
    else:
        # TODO: load the model without quantization
        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            device_map="auto",
            torch_dtype=torch.bfloat16,
            trust_remote_code=True,
        )
 
    results = []
    results_processed = []
    for case in dataset:
        prompt = case['prompt']

        # TODO: prompt the model and get the response
        if is_instruct:
            messages = [{
                "role": "user",
                "content": "Complete the following Python function. Return the complete "
                           "function in a single ```python code block.\n\n"
                           f"```python\n{prompt}\n```",
            }]
            input_ids = tokenizer.apply_chat_template(
                messages, add_generation_prompt=True, return_tensors="pt"
            ).to(model.device)
        else:
            input_ids = tokenizer(prompt, return_tensors="pt").input_ids.to(model.device)
        with torch.no_grad():
            outputs = model.generate(
                input_ids,
                attention_mask=torch.ones_like(input_ids),
                max_new_tokens=500,
                do_sample=False,  # greedy decoding == temperature 0
                eos_token_id=tokenizer.eos_token_id,
                pad_token_id=tokenizer.eos_token_id,
            )
        response = tokenizer.decode(outputs[0][input_ids.shape[1]:], skip_special_tokens=True)
        print(f"Task_ID {case['task_id']}:\nPrompt:\n{prompt}\nResponse:\n{response}")
        results.append(dict(task_id=case["task_id"], completion=response))

        # TODO: postprocessing may be required to handle extraneous output, fix indentation issues generated by the model, or handle other similar, trivial issues
        entry_point = case["entry_point"]
        code = response
        if is_instruct:
            blocks = re.findall(r"```[^\n]*\n(.*?)```", response, re.DOTALL)
            if not blocks:
                m = re.search(r"```[^\n]*\n(.*)", response, re.DOTALL)
                blocks = [m.group(1)] if m else [response]
            code = next((b for b in blocks if f"def {entry_point}" in b), blocks[0])
 
        if is_instruct and f"def {entry_point}" in code:
            try:
                tree = ast.parse(code)
                lines = code.split("\n")
                kept = []
                for node in tree.body:
                    keep = isinstance(node, (ast.Import, ast.ImportFrom, ast.FunctionDef,
                                             ast.AsyncFunctionDef, ast.ClassDef))
                    if isinstance(node, ast.Assign):
                        keep = not any(isinstance(n, ast.Call) for n in ast.walk(node))
                    if keep:
                        start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])]) - 1
                        kept.append("\n".join(lines[start:node.end_lineno]))
                code = "\n\n".join(kept) + "\n"
            except SyntaxError:
                pass
            processed = "\n" + code
        else:
            #stop at the 1st unindented line after the first line
            body_lines = code.lstrip("\n").split("\n")
            kept = [body_lines[0]]
            for line in body_lines[1:]:
                if line.strip() and not line[0].isspace():
                    break
                kept.append(line)
            first = kept[0]
            rest = "\n".join(kept[1:]).rstrip() + "\n"
            body = (first + "\n" + rest).rstrip() + "\n"
            # use the first variant that makes prompt + body valid Python
            candidates = [
                body,
                "    " + first.lstrip() + "\n" + rest,
                "    " + first.lstrip() + "\n" + textwrap.indent(textwrap.dedent(rest), "    "),
                "    " + first.lstrip() + "\n" + textwrap.indent(textwrap.dedent(rest), "        "),
                textwrap.indent(textwrap.dedent(body), "    "),
                body.expandtabs(4),
            ]
            processed = body
            for candidate in candidates:
                try:
                    compile(prompt + candidate, "<candidate>", "exec")
                    processed = candidate
                    break
                except Exception:
                    continue
 
        response_processed = processed
        results_processed.append(dict(task_id=case["task_id"], completion=response_processed))
    return results, results_processed

def read_jsonl(file_path):
    dataset = []
    with jsonlines.open(file_path) as reader:
        for line in reader: 
            dataset.append(line)
    return dataset

def write_jsonl(results, file_path):
    with jsonlines.open(file_path, "w") as f:
        for item in results:
            f.write_all([item])

if __name__ == "__main__":
    """
    This Python script is to run prompt LLMs for code synthesis.
    Usage:
    `python3 model_prompting.py <input_dataset> <model> <output_file> <output_file_processed> <if_quantization> `|& tee prompt.log

    Inputs:
    - <input_dataset>: A `.jsonl` file, which should be your team's dataset containing 20 HumanEval problems.
    - <model>: Specify the model to use. Options are "deepseek-ai/deepseek-coder-6.7b-base" or "deepseek-ai/deepseek-coder-6.7b-instruct".
    - <output_file>: A `.jsonl` file where the results will be saved.
    - <output_file_processed>: A `.jsonl` file where the processed results will be saved
    - <if_quantization>: Set to 'True' or 'False' to enable or disable model quantization.
    
    Outputs:
    - You can check <output_file> and  <output_file_processed> for detailed information.
    """
    args = sys.argv[1:]
    input_dataset = args[0]
    model = args[1]
    output_file = args[2]
    output_file_processed = args[3]
    if_quantization = args[4] # True or False

    if not input_dataset.endswith(".jsonl"):
        raise ValueError(f"{input_dataset} should be a `.jsonl` file!")
    
    if not output_file.endswith(".jsonl"):
        raise ValueError(f"{output_file} should be a `.jsonl` file!")
    
    quantization = True if if_quantization == "True" else False

    dataset = read_jsonl(input_dataset)
    results, results_processed = prompt_model(dataset, model, quantization)
    write_jsonl(results, output_file)
    write_jsonl(results_processed, output_file_processed)
