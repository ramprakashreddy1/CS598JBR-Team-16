"""MP3 Task 1: translate HumanEval-X Python solutions to Java and test them."""

import json
import os
import re
import subprocess
import sys
import tempfile

os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")


COMPILE_TIMEOUT_SECONDS = 30
RUN_TIMEOUT_SECONDS = 30
MAX_NEW_TOKENS = 1536

VANILLA_TEMPLATE = """Can you translate the following Python code into Java?
The new Java code must be enclosed between [Java Start] and [Java End].
Return a complete `class Solution` containing the translated method.

{python_code}"""

CRAFTED_TEMPLATE = """You are translating a Python HumanEval solution into Java.

Problem and Python implementation:
```python
{python_code}
```

The required Java declaration is:
```java
{java_declaration}
```

Before writing the answer, silently verify all of the following:
1. Preserve the exact behavior of the Python implementation, including boundary cases and early returns.
2. Preserve the Java method name, parameter types, return type, and `class Solution` shown in the declaration.
3. Translate Python collection, string, indexing, slicing, numeric, division, modulo, sorting, and mutation semantics carefully.
4. Produce self-contained compilable Java. Do not add a `main` method, tests, package declaration, or a public top-level class.
5. Use standard-library imports when needed.

Return only the complete Java `class Solution`, enclosed exactly between [Java Start] and [Java End]."""


def save_file(content, file_path):
    with open(file_path, "w", encoding="utf-8") as file:
        file.write(content)


def read_jsonl(file_path):
    with open(file_path, encoding="utf-8") as file:
        return [json.loads(line) for line in file if line.strip()]


def write_jsonl(results, file_path):
    with open(file_path, "w", encoding="utf-8") as file:
        for item in results:
            file.write(json.dumps(item, ensure_ascii=False) + "\n")


def derive_java_dataset_path(python_dataset_path):
    """Derive the paired HumanEval-X Java dataset generated by the provided script."""
    name = os.path.basename(python_dataset_path)
    if "humanevalx_python" not in name:
        raise ValueError(
            "Task 1 input must be named selected_humanevalx_python_<seed>.jsonl "
            "so the matching Java dataset can be located."
        )
    return os.path.join(
        os.path.dirname(os.path.abspath(python_dataset_path)),
        name.replace("humanevalx_python", "humanevalx_java"),
    )


def index_by_task_id(dataset):
    indexed = {entry["task_id"]: entry for entry in dataset}
    if len(indexed) != len(dataset):
        raise ValueError("Dataset contains duplicate task IDs")
    return indexed


def python_program(entry):
    return (entry["prompt"] + entry["canonical_solution"]).strip()


def build_instruction(python_entry, java_entry, vanilla):
    template = VANILLA_TEMPLATE if vanilla else CRAFTED_TEMPLATE
    values = {"python_code": python_program(python_entry)}
    if not vanilla:
        values["java_declaration"] = java_entry["declaration"].strip()
    return template.format(**values)


def extract_java(response):
    """Extract Java while tolerating common marker and Markdown variations."""
    marked = re.search(
        r"\[Java\s+Start\](.*?)\[Java\s+End\]", response, re.IGNORECASE | re.DOTALL
    )
    if marked:
        return marked.group(1).strip()

    fenced = re.findall(r"```(?:java)?\s*(.*?)```", response, re.IGNORECASE | re.DOTALL)
    if fenced:
        candidates = [block.strip() for block in fenced if block.strip()]
        class_blocks = [block for block in candidates if re.search(r"\bclass\s+Solution\b", block)]
        return (class_blocks[0] if class_blocks else candidates[0]) if candidates else ""

    start = re.search(r"\[Java\s+Start\]", response, re.IGNORECASE)
    return response[start.end():].strip() if start else response.strip()


def _balanced_class(source, class_name="Solution"):
    """Return one balanced class declaration, or None if it cannot be found."""
    match = re.search(rf"(?:public\s+)?class\s+{re.escape(class_name)}\b", source)
    if not match:
        return None
    brace = source.find("{", match.end())
    if brace < 0:
        return None
    depth = 0
    state = "code"
    index = brace
    while index < len(source):
        char = source[index]
        following = source[index + 1] if index + 1 < len(source) else ""
        if state == "line_comment":
            if char == "\n":
                state = "code"
            index += 1
            continue
        if state == "block_comment":
            if char == "*" and following == "/":
                state = "code"
                index += 2
            else:
                index += 1
            continue
        if state in {"string", "character"}:
            if char == "\\":
                index += 2
                continue
            expected = '"' if state == "string" else "'"
            if char == expected:
                state = "code"
            index += 1
            continue
        if char == "/" and following == "/":
            state = "line_comment"
            index += 2
            continue
        if char == "/" and following == "*":
            state = "block_comment"
            index += 2
            continue
        if char == '"':
            state = "string"
            index += 1
            continue
        if char == "'":
            state = "character"
            index += 1
            continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return source[match.start():index + 1]
        index += 1
    return source[match.start():]


def normalize_solution(java_code):
    """Apply structural cleanup without changing the generated algorithm."""
    code = java_code.replace("\ufeff", "").strip()
    code = re.sub(r"^```(?:java)?\s*", "", code, flags=re.IGNORECASE)
    code = re.sub(r"\s*```$", "", code).strip()
    code = re.sub(r"(?m)^\s*package\s+[\w.]+\s*;\s*$", "", code)
    code = re.sub(r"(?m)^\s*import\s+[^;]+;\s*$", "", code)

    solution_class = _balanced_class(code)
    if solution_class:
        return re.sub(r"^\s*public\s+class\s+Solution", "class Solution", solution_class, count=1)

    # Renaming a generated wrapper class is another structural repair explicitly
    # allowed by the assignment. Do not otherwise edit the implementation.
    other_class = re.search(r"(?:public\s+)?class\s+(\w+)\b", code)
    if other_class:
        class_name = other_class.group(1)
        class_source = _balanced_class(code, class_name)
        if class_source:
            return re.sub(
                rf"^\s*(?:public\s+)?class\s+{re.escape(class_name)}",
                "class Solution",
                class_source,
                count=1,
            )
    return "class Solution {\n" + code + "\n}"


def build_java_source(java_entry, generated_code):
    imports = "\n".join(
        [
            "import java.util.*;",
            "import java.lang.*;",
            "import java.math.*;",
            "import java.io.*;",
            "import java.util.stream.*;",
        ]
    )
    solution = normalize_solution(generated_code)
    return f"{imports}\n\n{solution}\n\n{java_entry['test'].strip()}\n"


def evaluate_java(java_entry, response):
    """Compile and run one generated solution in an isolated temporary directory."""
    extracted = extract_java(response)
    if not extracted:
        return {
            "is_correct": False,
            "failure_type": "extraction_error",
            "details": "No Java code was found in the model response.",
            "extracted_code": "",
        }

    source = build_java_source(java_entry, extracted)
    try:
        with tempfile.TemporaryDirectory(prefix="mp3_java_") as temp_dir:
            source_path = os.path.join(temp_dir, "Main.java")
            save_file(source, source_path)
            try:
                compiled = subprocess.run(
                    ["javac", "-encoding", "UTF-8", "Main.java"],
                    cwd=temp_dir,
                    capture_output=True,
                    text=True,
                    timeout=COMPILE_TIMEOUT_SECONDS,
                )
            except subprocess.TimeoutExpired:
                return {
                    "is_correct": False,
                    "failure_type": "compilation_timeout",
                    "details": f"javac exceeded {COMPILE_TIMEOUT_SECONDS} seconds.",
                    "extracted_code": extracted,
                }
            if compiled.returncode != 0:
                return {
                    "is_correct": False,
                    "failure_type": "compilation_error",
                    "details": (compiled.stdout + "\n" + compiled.stderr).strip()[-6000:],
                    "extracted_code": extracted,
                }

            try:
                executed = subprocess.run(
                    ["java", "-cp", temp_dir, "Main"],
                    cwd=temp_dir,
                    capture_output=True,
                    text=True,
                    timeout=RUN_TIMEOUT_SECONDS,
                )
            except subprocess.TimeoutExpired:
                return {
                    "is_correct": False,
                    "failure_type": "test_timeout",
                    "details": f"Java tests exceeded {RUN_TIMEOUT_SECONDS} seconds.",
                    "extracted_code": extracted,
                }
            if executed.returncode != 0:
                return {
                    "is_correct": False,
                    "failure_type": "test_failure",
                    "details": (executed.stdout + "\n" + executed.stderr).strip()[-6000:],
                    "extracted_code": extracted,
                }
    except FileNotFoundError as error:
        raise RuntimeError("Java JDK not found. Install `javac` and `java` before running Task 1.") from error

    return {
        "is_correct": True,
        "failure_type": "pass",
        "details": "Compilation and all Java tests passed.",
        "extracted_code": extracted,
    }


def load_model(model_name):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig

    if not torch.cuda.is_available():
        raise RuntimeError(
            "DeepSeekCoder-6.7B 4-bit inference requires an NVIDIA GPU. "
            "In Colab choose Runtime > Change runtime type > T4 GPU."
        )
    capability_major, _ = torch.cuda.get_device_capability()
    compute_dtype = (
        torch.bfloat16
        if capability_major >= 8 and torch.cuda.is_bf16_supported()
        else torch.float16
    )
    print(f"GPU: {torch.cuda.get_device_name(0)}")
    print(f"4-bit compute dtype: {compute_dtype}")
    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
    quantization = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_use_double_quant=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_compute_dtype=compute_dtype,
    )
    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        quantization_config=quantization,
        device_map="auto",
        torch_dtype=compute_dtype,
        low_cpu_mem_usage=True,
        trust_remote_code=True,
    )
    model.eval()
    return tokenizer, model


def generate_response(model, tokenizer, instruction):
    import torch

    prompt = tokenizer.apply_chat_template(
        [{"role": "user", "content": instruction}],
        add_generation_prompt=True,
        tokenize=False,
    )
    inputs = tokenizer(prompt, return_tensors="pt", add_special_tokens=False).to(model.device)
    with torch.inference_mode():
        outputs = model.generate(
            **inputs,
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=False,
            eos_token_id=tokenizer.eos_token_id,
            pad_token_id=tokenizer.eos_token_id,
        )
    response = tokenizer.decode(outputs[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True)
    del outputs, inputs
    torch.cuda.empty_cache()
    return prompt, response


def prompt_model(
    dataset,
    model_name="deepseek-ai/deepseek-coder-6.7b-instruct",
    vanilla=True,
    java_dataset=None,
    output_file=None,
):
    if java_dataset is None:
        raise ValueError("The paired Java dataset is required for evaluation.")
    print(f"Working with {model_name}; vanilla={vanilla}")
    java_entries = index_by_task_id(java_dataset)
    missing = [entry["task_id"] for entry in dataset if entry["task_id"] not in java_entries]
    if missing:
        raise ValueError(f"Java dataset is missing task IDs: {missing}")

    tokenizer, model = load_model(model_name)
    resume = os.environ.get("MP3_RESUME") == "1"
    completed = {}
    if resume and output_file and os.path.exists(output_file):
        completed = index_by_task_id(read_jsonl(output_file))
        print(f"Resuming from {len(completed)} completed Task 1 entries in {output_file}")
    results = []
    for entry in dataset:
        if entry["task_id"] in completed:
            print(f"Skipping completed Task_ID {entry['task_id']}")
            results.append(completed[entry["task_id"]])
            continue
        java_entry = java_entries[entry["task_id"]]
        instruction = build_instruction(entry, java_entry, vanilla)
        prompt, response = generate_response(model, tokenizer, instruction)
        evaluation = evaluate_java(java_entry, response)

        print(f"\nTask_ID {entry['task_id']}")
        print(f"prompt:\n{prompt}\nresponse:\n{response}")
        print(f"is_correct: {evaluation['is_correct']}")
        print(f"failure_type: {evaluation['failure_type']}")
        print(f"details:\n{evaluation['details']}")

        results.append(
            {
                "task_id": entry["task_id"],
                "prompt": prompt,
                "response": response,
                "is_correct": evaluation["is_correct"],
                "failure_type": evaluation["failure_type"],
            }
        )
        if output_file:
            write_jsonl(results, output_file)
    return results


def main(args):
    if len(args) != 4:
        raise SystemExit(
            "Usage: python3 task_1.py <python_dataset.jsonl> <model> "
            "<output.jsonl> <True|False>"
        )
    input_dataset, model_name, output_file, vanilla_text = args
    if not input_dataset.endswith(".jsonl") or not output_file.endswith(".jsonl"):
        raise ValueError("Input and output files must use the .jsonl extension.")
    if vanilla_text not in {"True", "False"}:
        raise ValueError("<if_vanilla> must be exactly True or False.")

    java_dataset_path = derive_java_dataset_path(input_dataset)
    if not os.path.exists(java_dataset_path):
        raise FileNotFoundError(
            f"Paired Java dataset not found: {java_dataset_path}. "
            "Run humanevalx_dataset_generation.py first."
        )
    dataset = read_jsonl(input_dataset)
    java_dataset = read_jsonl(java_dataset_path)
    if len(dataset) != 20 or len(java_dataset) != 20:
        raise ValueError("Task 1 requires exactly 20 Python and 20 Java entries.")
    results = prompt_model(
        dataset,
        model_name,
        vanilla_text == "True",
        java_dataset=java_dataset,
        output_file=output_file,
    )
    write_jsonl(results, output_file)


if __name__ == "__main__":
    main(sys.argv[1:])
